"""Start PayPal's local MCP server, call tools/list, and write the tool catalog to docs/.

    python scripts/paypal_tools_list.py            # mint a sandbox token from .env, then list
    python scripts/paypal_tools_list.py --no-auth  # list with a placeholder token (no PayPal call)

Listing tools doesn't call PayPal, so --no-auth works before sandbox credentials exist.
"""

import argparse
import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))

from intentguard.config import REPO_ROOT, get_settings  # noqa: E402
from intentguard.paypal.auth import TokenProvider  # noqa: E402
from intentguard.paypal.mcp_client import paypal_mcp_session  # noqa: E402

DOCS = REPO_ROOT / "docs"


def render_markdown(tools: list[dict]) -> str:
    lines = [
        "# PayPal MCP tool catalog",
        "",
        "Generated by `scripts/paypal_tools_list.py` from `@paypal/mcp` (version pinned in `paypal-mcp/package.json`).",
        "Full input schemas: [paypal-mcp-tools.json](paypal-mcp-tools.json).",
        "",
        "| Tool | Required args | Description |",
        "|---|---|---|",
    ]
    for tool in tools:
        required = ", ".join(f"`{name}`" for name in tool["inputSchema"].get("required", [])) or "—"
        description = " ".join((tool.get("description") or "").split())
        lines.append(f"| `{tool['name']}` | {required} | {description} |")
    return "\n".join(lines) + "\n"


async def main(no_auth: bool) -> None:
    settings = get_settings()
    if no_auth:
        token = "placeholder-token"
    else:
        token = TokenProvider(settings).get()
        print("Sandbox access token minted OK.")

    async with paypal_mcp_session(token, settings.paypal_environment) as session:
        result = await session.list_tools()

    tools = sorted(
        (tool.model_dump(mode="json", by_alias=True, exclude_none=True) for tool in result.tools),
        key=lambda tool: tool["name"],
    )
    DOCS.mkdir(exist_ok=True)
    (DOCS / "paypal-mcp-tools.json").write_text(json.dumps(tools, indent=2) + "\n", encoding="utf-8")
    (DOCS / "paypal-mcp-tools.md").write_text(render_markdown(tools), encoding="utf-8")
    print(f"{len(tools)} tools: {', '.join(tool['name'] for tool in tools)}")
    print(f"Wrote {DOCS / 'paypal-mcp-tools.md'}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-auth", action="store_true", help="skip minting a token; use a placeholder")
    asyncio.run(main(parser.parse_args().no_auth))
